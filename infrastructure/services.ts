import {loadSnapshot} from './load-snapshot';
const snapshot=loadSnapshot();
import { SnapshotRepository } from './snapshot-repository.ts';
import { ForecastService } from '../application/forecast-service.ts';
import { ComparisonService } from '../application/comparison-service.ts';
import { AccuracyService } from '../application/accuracy-service.ts';
import { ALIGNMENT_NOTE } from '../domain/time.ts';
const repository = new SnapshotRepository(snapshot);
const forecasts = new ForecastService(repository, repository, snapshot.meta.snapshot_id);
export const services = { forecasts, comparison: new ComparisonService(forecasts), accuracy: new AccuracyService(forecasts) };
export const metadata = { ...snapshot.meta, alignment_note: ALIGNMENT_NOTE };
